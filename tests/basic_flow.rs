#[tokio::test]
async fn out_of_band_approval_mode_blocks_mcp_decisions() {
    use mcp_orca::config::ApprovalMode;

    let td = tempdir().unwrap();
    let mut cfg = Config::default();
    cfg.workspace.root = td.path().join("ws").to_string_lossy().to_string();
    cfg.profiles.use_os_defaults = false;
    cfg.profiles.search_paths = vec![];
    cfg.approval.mode = ApprovalMode::OutOfBand;

    let ctx = Arc::new(ToolContext::new(cfg).unwrap());
    let registry = ToolRegistry::new();

    let import = registry
        .call(
            &ctx,
            "orca_artifact_import",
            Some(json!({
                "name": "note.txt", "kind": "other", "format": "txt",
                "data": base64::Engine::encode(&base64::engine::general_purpose::STANDARD, b"hello")
            })),
        )
        .await
        .unwrap();
    let art_id = import.structured_content.as_ref().unwrap()["artifact"]["id"]
        .as_str()
        .unwrap()
        .to_string();

    // Gated call creates a pending request.
    let blocked = registry
        .call(
            &ctx,
            "orca_artifact_delete",
            Some(json!({"artifact_id": art_id})),
        )
        .await;
    assert!(blocked.is_err());
    let pending = registry
        .call(&ctx, "orca_pending_approvals", None)
        .await
        .unwrap();
    let approval_id = pending.structured_content.as_ref().unwrap()["pending"][0]["id"]
        .as_str()
        .unwrap()
        .to_string();

    // In-band decision is refused.
    let refused = registry
        .call(
            &ctx,
            "orca_approval_decide",
            Some(json!({"approval_id": approval_id, "approve": true})),
        )
        .await;
    let message = refused.unwrap_err().public_message();
    assert!(message.contains("out_of_band"), "message: {message}");

    // Out-of-band decision (host CLI path) still works, then the retry succeeds.
    ctx.approvals
        .decide(&approval_id, true, Some("decided on host".into()))
        .unwrap();
    let deleted = registry
        .call(
            &ctx,
            "orca_artifact_delete",
            Some(json!({"artifact_id": art_id})),
        )
        .await
        .unwrap();
    assert_eq!(
        deleted.structured_content.as_ref().unwrap()["deleted"],
        true
    );
}

