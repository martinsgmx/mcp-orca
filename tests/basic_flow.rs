#[tokio::test]
async fn slice_job_completes_with_configured_engine_and_produces_gcode_artifact() {
    use std::os::unix::fs::PermissionsExt;

    let td = tempdir().unwrap();
    let script = td.path().join("fake-slicer.sh");
    std::fs::write(
        &script,
        "#!/bin/sh\n# argv: <output-gcode> <model...>\nset -eu\necho 'fake slicer got:' \"$@\"\nprintf '; generated by fake slicer\\n; env=%s\\nG28\\nG1 X10 Y10 E1\\n' \"${MCP_ORCA_TEST_ENV:-missing}\" > \"$1\"\n",
    )
    .unwrap();
    std::fs::set_permissions(&script, std::fs::Permissions::from_mode(0o755)).unwrap();

    let mut cfg = Config::default();
    cfg.workspace.root = td.path().join("ws").to_string_lossy().to_string();
    cfg.profiles.use_os_defaults = false;
    cfg.profiles.search_paths = vec![];
    cfg.engine.binary = script.to_string_lossy().to_string();
    cfg.engine.slice_command = vec!["{binary}".into(), "{gcode}".into(), "{models}".into()];
    cfg.engine
        .env
        .insert("MCP_ORCA_TEST_ENV".into(), "hello-from-env".into());

    let ctx = Arc::new(ToolContext::new(cfg).unwrap());
    let registry = ToolRegistry::new();

    let stl = "solid t\n  facet normal 0 0 1\n    outer loop\n      vertex 0 0 0\n      vertex 1 0 0\n      vertex 0 1 0\n    endloop\n  endfacet\nendsolid t\n";
    let b64 = base64::Engine::encode(&base64::engine::general_purpose::STANDARD, stl.as_bytes());
    let import = registry
        .call(
            &ctx,
            "orca_artifact_import",
            Some(json!({
                "name": "tri.stl", "kind": "mesh", "format": "stl", "data": b64
            })),
        )
        .await
        .unwrap();
    let art_id = import.structured_content.as_ref().unwrap()["artifact"]["id"]
        .as_str()
        .unwrap()
        .to_string();

    let process = registry
        .call(
            &ctx,
            "orca_profile_create",
            Some(json!({
                "name": "fake-process", "kind": "process",
                "settings": {"layer_height": 0.24, "nozzle_temperature": 205}
            })),
        )
        .await
        .unwrap();
    let process_id = process.structured_content.as_ref().unwrap()["artifact"]["id"]
        .as_str()
        .unwrap()
        .to_string();

    let slice = registry
        .call(
            &ctx,
            "orca_slice",
            Some(json!({
                "model_artifact_ids": [art_id],
                "printer": "generic_printer",
                "filament": "generic_pla",
                "process": process_id,
                "overrides": {"sparse_infill_density": 15, "nozzle_temperature": 210},
                "wait": true,
                "wait_timeout_secs": 30
            })),
        )
        .await
        .unwrap();
    assert_eq!(slice.is_error, Some(false));
    let body = slice.structured_content.as_ref().unwrap();
    assert_eq!(body["state"], "completed", "job body: {body:?}");
    let gcode_id = body["gcode_artifact"].as_str().unwrap().to_string();
    let job_id = body["id"].as_str().unwrap().to_string();

    // Merged settings (workspace profile + overrides) are staged for the adapter.
    let settings: serde_json::Value = serde_json::from_str(
        &std::fs::read_to_string(ctx.store.job_dir(&job_id).join("settings.json")).unwrap(),
    )
    .unwrap();
    assert_eq!(settings["layer_height"], 0.24);
    assert_eq!(settings["nozzle_temperature"], 210);
    assert_eq!(settings["sparse_infill_density"], 15);

    let read = registry
        .call(
            &ctx,
            "orca_gcode_inspect",
            Some(json!({"artifact_id": gcode_id})),
        )
        .await
        .unwrap();
    assert_eq!(read.is_error, Some(false));
    let gcode = &read.structured_content.as_ref().unwrap()["gcode"];
    assert_eq!(gcode["lines"], 4);
    assert_eq!(gcode["commands"], 2);
    assert!((gcode["filament_used_mm"].as_f64().unwrap() - 1.0).abs() < 1e-9);

    let text = registry
        .call(
            &ctx,
            "orca_artifact_read_text",
            Some(json!({"artifact_id": gcode_id})),
        )
        .await
        .unwrap();
    let body = text.structured_content.as_ref().unwrap();
    assert!(
        body["text"].as_str().unwrap().contains("hello-from-env"),
        "env should reach the slicer process: {body:?}"
    );
}

#[tokio::test]
async fn mesh_transform_and_merge_produce_derived_artifacts() {
    let td = tempdir().unwrap();
    let mut cfg = Config::default();
    cfg.workspace.root = td.path().join("ws").to_string_lossy().to_string();
    cfg.profiles.use_os_defaults = false;
    cfg.profiles.search_paths = vec![];

    let ctx = Arc::new(ToolContext::new(cfg).unwrap());
    let registry = ToolRegistry::new();

    let stl = "solid t\n  facet normal 0 0 1\n    outer loop\n      vertex 0 0 0\n      vertex 2 0 0\n      vertex 0 2 0\n    endloop\n  endfacet\nendsolid t\n";
    let b64 = base64::Engine::encode(&base64::engine::general_purpose::STANDARD, stl.as_bytes());
    let import = registry
        .call(
            &ctx,
            "orca_artifact_import",
            Some(json!({
                "name": "square.stl", "kind": "mesh", "format": "stl", "data": b64
            })),
        )
        .await
        .unwrap();
    let source_id = import.structured_content.as_ref().unwrap()["artifact"]["id"]
        .as_str()
        .unwrap()
        .to_string();

    let transformed = registry
        .call(
            &ctx,
            "orca_mesh_transform",
            Some(json!({
                "artifact_id": source_id,
                "translate": [10.0, 0.0, 0.0],
                "scale": 2.0,
                "name": "square-moved.stl"
            })),
        )
        .await
        .unwrap();
    assert_eq!(transformed.is_error, Some(false));
    let body = transformed.structured_content.as_ref().unwrap();
    let moved_id = body["artifact"]["id"].as_str().unwrap().to_string();
    assert_eq!(body["mesh"]["triangles"], 1);
    assert_eq!(body["mesh"]["bounds_min"], json!([10.0, 0.0, 0.0]));
    assert_eq!(body["mesh"]["bounds_max"], json!([14.0, 4.0, 0.0]));

    let merged = registry
        .call(
            &ctx,
            "orca_mesh_merge",
            Some(json!({"artifact_ids": [source_id, moved_id], "name": "both.stl"})),
        )
        .await
        .unwrap();
    assert_eq!(merged.is_error, Some(false));
    let merged_body = merged.structured_content.as_ref().unwrap();
    assert_eq!(merged_body["mesh"]["triangles"], 2);
    assert_eq!(merged_body["mesh"]["bounds_min"], json!([0.0, 0.0, 0.0]));
    assert_eq!(merged_body["mesh"]["bounds_max"], json!([14.0, 4.0, 0.0]));

    // Unsupported/non-mesh input should fail clearly.
    let missing = registry
        .call(
            &ctx,
            "orca_mesh_transform",
            Some(json!({"artifact_id": source_id, "scale": 1.0})),
        )
        .await;
    assert!(missing.is_err());
}

#[tokio::test]
async fn destructive_tool_requires_and_consumes_approval() {
    let td = tempdir().unwrap();
    let mut cfg = Config::default();
    cfg.workspace.root = td.path().join("ws").to_string_lossy().to_string();
    cfg.profiles.use_os_defaults = false;
    cfg.profiles.search_paths = vec![];

    let ctx = Arc::new(ToolContext::new(cfg).unwrap());
    let registry = ToolRegistry::new();

    let import = registry
        .call(
            &ctx,
            "orca_artifact_import",
            Some(json!({
                "name": "note.txt", "kind": "other", "format": "txt",
                "data": base64::Engine::encode(&base64::engine::general_purpose::STANDARD, b"hello")
            })),
        )
        .await
        .unwrap();
    let art_id = import.structured_content.as_ref().unwrap()["artifact"]["id"]
        .as_str()
        .unwrap()
        .to_string();

    let blocked = registry
        .call(
            &ctx,
            "orca_artifact_delete",
            Some(json!({"artifact_id": art_id})),
        )
        .await;
    assert!(blocked.is_err());
    let message = blocked.unwrap_err().public_message();
    assert!(message.contains("requires approval"), "message: {message}");

    let pending = registry
        .call(&ctx, "orca_pending_approvals", None)
        .await
        .unwrap();
    let pending_body = pending.structured_content.as_ref().unwrap();
    assert_eq!(pending_body["count"], 1, "pending: {pending_body:?}");
    let approval_id = pending_body["pending"][0]["id"]
        .as_str()
        .unwrap()
        .to_string();
    assert_eq!(pending_body["pending"][0]["tool"], "orca_artifact_delete");

    let decision = registry
        .call(
            &ctx,
            "orca_approval_decide",
            Some(json!({"approval_id": approval_id, "approve": true, "note": "test"})),
        )
        .await
        .unwrap();
    assert_eq!(
        decision.structured_content.as_ref().unwrap()["approval"]["status"],
        "approved"
    );

    let deleted = registry
        .call(
            &ctx,
            "orca_artifact_delete",
            Some(json!({"artifact_id": art_id})),
        )
        .await
        .unwrap();
    assert_eq!(
        deleted.structured_content.as_ref().unwrap()["deleted"],
        true
    );

    // The approval is consumed once; a second identical delete needs approval again.
    let again = registry
        .call(
            &ctx,
            "orca_artifact_delete",
            Some(json!({"artifact_id": art_id})),
        )
        .await;
    assert!(again.is_err());
}

